//! Regenerates Solar's Unicode predicates with the repository's Rust toolchain.
//!
//! Run `rustc tools/generate_unicode.rs -o /tmp/solar-unicode-gen`, then
//! `/tmp/solar-unicode-gen src/std/unicode_data.solar`, and finally
//! `cargo run -- fmt src/std/unicode_data.solar`.
use std::fmt::Write;

fn emit(out: &mut String, ranges: &[(u32, u32)], depth: usize) {
    let indent = "\t".repeat(depth);
    if ranges.is_empty() {
        writeln!(out, "{indent}false").unwrap();
        return;
    }
    if ranges.len() == 1 {
        let (low, high) = ranges[0];
        if low == high {
            writeln!(out, "{indent}code == {low}u32").unwrap();
        } else {
            writeln!(out, "{indent}code >= {low}u32 && code <= {high}u32").unwrap();
        }
        return;
    }
    let middle = ranges.len() / 2;
    let (low, high) = ranges[middle];
    writeln!(out, "{indent}if code < {low}u32 {{").unwrap();
    emit(out, &ranges[..middle], depth + 1);
    writeln!(out, "{indent}}} else {{").unwrap();
    writeln!(out, "{indent}\tif code > {high}u32 {{").unwrap();
    emit(out, &ranges[middle + 1..], depth + 2);
    writeln!(out, "{indent}\t}} else {{ true }}").unwrap();
    writeln!(out, "{indent}}}").unwrap();
}

fn main() {
    let mut output = format!(
        "// Generated by tools/generate_unicode.rs using Unicode {}.{}.{}.\n// Do not edit by hand. Predicates use balanced decisions without allocating.\n",
        char::UNICODE_VERSION.0, char::UNICODE_VERSION.1, char::UNICODE_VERSION.2,
    );
    for (name, predicate) in [
        ("is_alphabetic", char::is_alphabetic as fn(char) -> bool),
        ("is_numeric", char::is_numeric),
        ("is_uppercase", char::is_uppercase),
        ("is_whitespace", char::is_whitespace),
    ] {
        let mut ranges = Vec::new();
        let mut start = None;
        for code in 0..=0x110000 {
            if char::from_u32(code).is_some_and(predicate) {
                start.get_or_insert(code);
            } else if let Some(low) = start.take() {
                ranges.push((low, code - 1));
            }
        }
        writeln!(output, "\n/// Unicode predicate generated from Rust's character tables.\npub fn {name}(code: Uint32) -> Bool {{").unwrap();
        emit(&mut output, &ranges, 1);
        output.push_str("}\n");
    }
    std::fs::write(std::env::args().nth(1).unwrap(), output).unwrap();
}
